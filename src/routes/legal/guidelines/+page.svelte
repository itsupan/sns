<h1>Community Guidelines</h1>
<p class="lede">
	Kizuna (絆) means the bonds between people. These guidelines keep it a calm place to share
	photography and writing.
</p>

<h2>Be kind</h2>
<ul>
	<li>Critique the work, not the person. Keep feedback constructive.</li>
	<li>No harassment, bullying, threats, or targeting people with repeated unwanted contact.</li>
	<li>
		No hate speech or slurs aimed at people because of race, ethnicity, religion, gender, sexual
		orientation, disability or other protected traits.
	</li>
</ul>

<h2>Share what is yours</h2>
<ul>
	<li>Post only photos and text you made or have permission to share, and credit others.</li>
	<li>Respect people's privacy. Ask before posting clear photos of private individuals.</li>
	<li>Never share someone's private information, such as their address or phone number.</li>
</ul>

<h2>Keep it safe</h2>
<ul>
	<li>
		No sexual content involving minors. We remove it immediately and report it to the authorities.
	</li>
	<li>No nudity or sexual content shared without consent, and no graphic violence or gore.</li>
	<li>No content that promotes self-harm, terrorism or dangerous activities.</li>
	<li>No scams, spam, fake engagement or impersonation.</li>
</ul>

<h2>If you see something</h2>
<p>
	Use <strong>Report</strong> on a post, comment, message or profile, and <strong>Block</strong> anyone
	you don't want to hear from. We review reports and may remove content, restrict features or close accounts.
	Serious or repeated violations lead to a permanent ban.
</p>

